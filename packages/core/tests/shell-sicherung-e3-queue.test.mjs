import assert from'node:assert/strict';import{randomUUID}from'node:crypto';
const u=new URL(process.env.DATABASE_URL||'http://invalid');assert.equal(u.pathname,'/synapse_test');assert.equal(u.port,'5433');
const{getPool,closePool}=await import('../dist/db/client.js');
const{enqueueShellJob,getShellJobById}=await import('../dist/services/shell-queue.js');
const project='test-e3-queue-'+randomUUID(),root=process.cwd();
await getPool().query('INSERT INTO projects(name,hostname,path)VALUES($1,$2,$3)',[project,'test',root]);
const args={project,command:'pwd',agent_id:'sol-2',target:'local'};
const first=await enqueueShellJob(args);
assert.equal(Object.hasOwn(await getShellJobById(first.id),'sicherung'),false,'Normalantwort enthält kein neues leeres Feld');
const before=await enqueueShellJob(args);assert.equal(before.attached,true,'Kontrollfall: gleicher normaler Aufruf wird angehängt');
await getPool().query("INSERT INTO shell_sicherungsregeln(id,version,art,stufe,muster,antwort_id,quelle,status,bereich,project,positiv,negativ)VALUES($1,1,'text','anleitung',$2::jsonb,'fs.rm','owned-test','aktiv','projekt',$3,'[]','[]')",['owned-'+randomUUID(),JSON.stringify({command:['^pwd$']}),project]);
const after=await enqueueShellJob(args);
assert.notEqual(after.id,first.id,'neue Regel darf nicht an ungeprüften alten Job anhängen');assert.equal(after.attached,undefined);
const grant={grund:'Eigene ungefährliche Queueprobe',befehl_hash:'a'.repeat(64),lage_hash:'b'.repeat(64),regelversion:'c'.repeat(64)};
const confirmed=await enqueueShellJob({...args,agent_id:'koordinator',bestaetigt:grant,shell:'bash'});
const row=await getShellJobById(confirmed.id);
assert.deepEqual(row.sicherung.anfrage.bestaetigt,grant);assert.equal(row.sicherung.anfrage.shell,'bash');
console.log('P10-T37 Queue: frische Regel vor Attach und Anfrage für native Prüfung grün.');
await closePool();process.exit(0);
