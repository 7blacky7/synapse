/** P10-T36: Lage nur lesen, keine Katalogbefehle ausführen. */
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,symlink}from'node:fs/promises';
import {join}from'node:path';import{homedir}from'node:os';
const {ermittleShellLage}=await import('../dist/services/shell-lage.js');
const {waehleShellStart}=await import('../dist/services/shell-start.js');
const root=await mkdtemp(join(homedir(),'dev','synapse-shell-e2-'));
await mkdir(join(root,'safe'));await writeFile(join(root,'safe','x.txt'),'owned fixture');
await symlink(join(root,'safe'),join(root,'link'),'dir');
const opts={shell:'bash',os:'linux',cwd:root,project_root:root,env:{ROOT:root,EMPTY:''}};
const read=(s,o={})=>ermittleShellLage(s,{...opts,...o});
const hit=(r)=>r.ziele[0];
let r=await read('rm -rf "$ROOT/safe"');
assert.equal(hit(r).kanonisch,join(root,'safe'));assert.equal(hit(r).im_projekt,true);assert.equal(hit(r).existiert,true);
r=await read('BASE="$ROOT"; rm -rf "$BASE/link/x.txt"');
assert.equal(hit(r).kanonisch,join(root,'safe','x.txt'));assert.ok(hit(r).links.length);
r=await read('rm -rf "$MISSING/safe"');
assert.ok(r.ungeklaert.some(x=>x.includes('variable_unbekannt')));assert.equal(hit(r).kanonisch,undefined);
r=await read('rm -rf "$EMPTY/"*');
assert.equal(hit(r).wurzel,true);assert.ok(hit(r).leere_variablen.includes('EMPTY'));
r=await read('rm -rf "$ROOT/new/missing"');
assert.equal(hit(r).existiert,false);assert.equal(hit(r).naechster_elternpfad,root);
r=await read("cd safe && rm x.txt");
assert.equal(hit(r).kanonisch,join(root,'safe','x.txt'));
r=await read("cd absent; rm safe/x.txt");
assert.equal(hit(r).kanonisch,join(root,'safe','x.txt'));assert.ok(r.ungeklaert.includes('cd_nicht_verifiziert'));
r=await read('x=$(get_target); rm -rf "$x"');
assert.ok(r.ungeklaert.length);
r=await read("rm '$ROOT/safe'");
assert.equal(hit(r).expandiert,'$ROOT/safe','single quotes bleiben literal');
const win={shell:'pwsh',os:'windows',cwd:'C:\\work\\project',project_root:'C:\\work\\project',env:{},inspect:false};
r=await read('$ordner = ""; Remove-Item "$ordner\\*" -Recurse -Force',win);
assert.equal(hit(r).pfad,'C:\\*');assert.equal(hit(r).wurzel,true);assert.ok(hit(r).leere_variablen.includes('ordner'));
r=await read('$root = "C:\\work\\project"; $p = Join-Path $root "safe"; Remove-Item -LiteralPath $p -Recurse',win);
assert.equal(hit(r).pfad,'C:\\work\\project\\safe');assert.equal(hit(r).im_projekt,true);
r=await read('Remove-Item C:temp -Recurse',win);
assert.equal(hit(r).pfad,'C:\\work\\project\\temp');
r=await read('Remove-Item D:temp -Recurse',win);
assert.ok(r.ungeklaert.includes('laufwerks_cwd_unbekannt'));
r=await read('Remove-Item "\\\\server\\share\\*" -Recurse',win);
assert.equal(hit(r).unc,true);
r=await read('Remove-Item "\\\\.\\PhysicalDrive0" -Force',win);
assert.equal(hit(r).geraet,true);
r=await read('set "folder=" & rmdir /s /q "%folder%\\*"',{...win,shell:'cmd'});
assert.equal(hit(r).pfad,'C:\\*');assert.equal(hit(r).wurzel,true);
assert.equal(waehleShellStart(undefined,'win32').programm,'cmd.exe');
assert.equal(waehleShellStart('pwsh','win32').programm,'pwsh.exe');
assert.equal(waehleShellStart(undefined,'linux').programm,'sh');
assert.ok(r.hash);assert.equal((await read('rm "$ROOT/safe"')).hash,(await read('rm "$ROOT/safe"')).hash);

r=await read('Remove-Item HKLM:\\Software -Recurse',win);
assert.ok(r.ungeklaert.includes('provider_nicht_dateisystem'));
assert.equal(r.sicher_aufloesbar,false);assert.equal(r.hinweis,'Lage nicht sicher auflösbar');
r=await read('$p = Join-Path "C:\\work" "D:\\other"; Remove-Item $p',win);
assert.ok(r.ungeklaert.includes('join_path_absolute_komponente'));
r=await read('Remove-Item "$TEMP\\x"',{...win,env:{TEMP:'C:\\tmp'}});
assert.ok(r.ungeklaert.some(x=>x.includes('variable_unbekannt')));
r=await read('Remove-Item "$env:TEMP\\x"',{...win,env:{TEMP:'C:\\tmp'}});
assert.equal(hit(r).pfad,'C:\\tmp\\x');
r=await read('BASE=safe | cat; rm "$BASE/x"');
assert.ok(r.ungeklaert.includes('scope_nicht_verifiziert'));
assert.ok(r.ungeklaert.some(x=>x.includes('variable_unbekannt')));


r=await read('rm "${EMPTY-fallback}/safe"');
assert.equal(hit(r).pfad,'/safe','gesetzter leerer Wert nutzt keinen Minus-Fallback');
r=await read('rm ~other/safe');
assert.ok(r.ungeklaert.includes('tilde_benutzer_nicht_statisch'));

r=await read('false && BASE=safe; rm "$BASE/x"');
assert.equal(r.sicher_aufloesbar,false);assert.ok(r.ungeklaert.includes('scope_nicht_verifiziert'));
r=await read('if false; then BASE=safe; fi; rm "$BASE/x"');
assert.equal(r.sicher_aufloesbar,false);assert.ok(r.ungeklaert.includes('kontrollfluss_nicht_statisch'));
console.log('P10-T36 Variablen/Pfade/Links/Join/Wurzeln/UNC/Geräte/Windows-Shellwahl gruen.');
