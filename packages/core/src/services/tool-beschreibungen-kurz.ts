type Schema = { description?: string; inputSchema?: { properties?: Record<string, unknown> } };
type Prop = { description?: string; items?: { properties?: Record<string, unknown> } };

/** Kurztext fuer einen Parameter (Tool-Eintrag vor ALLGEMEIN); undefined = Original bleibt. */
export function kurzParameterText(tool: string, param: string): string | undefined {
  if (KURZ_AUSNAHMEN.has(param)) return undefined;
  return KURZ_BESCHREIBUNGEN[tool]?.p[param] ?? (param.includes('.') ? undefined : ALLGEMEIN[param]);
}

/**
 * Ersetzt in einer KOPIE die Beschreibungstexte (Tool + Parameter + eine Ebene items.properties).
 * Struktur bleibt unveraendert. Tools ohne Eintrag bleiben wie sie sind.
 */
export function kuerzeToolDefinition<T extends { name: string } & Schema>(def: T): T {
  const k = KURZ_BESCHREIBUNGEN[def.name];
  if (!k) return def;
  const kopie = structuredClone(def);
  kopie.description = k.b;
  const props = kopie.inputSchema?.properties ?? {};
  for (const [name, roh] of Object.entries(props)) {
    const prop = roh as Prop;
    if (!prop || typeof prop !== 'object') continue;
    const text = kurzParameterText(def.name, name);
    if (text !== undefined && typeof prop.description === 'string') prop.description = text;
    for (const [unter, uroh] of Object.entries(prop.items?.properties ?? {})) {
      const u = uroh as Prop;
      const ut = kurzParameterText(def.name, `${name}.${unter}`);
      if (ut !== undefined && u && typeof u === 'object' && typeof u.description === 'string') u.description = ut;
    }
  }
  return kopie;
}

/** Parameter mit Beschreibung, fuer die kein Kurztext existiert (Debug/Test). */
export function fehlendeKurztexte(defs: Array<{ name: string } & Schema>): Array<{ tool: string; parameter: string }> {
  const fehlen: Array<{ tool: string; parameter: string }> = [];
  for (const d of defs) {
    if (!KURZ_BESCHREIBUNGEN[d.name]) { fehlen.push({ tool: d.name, parameter: '*' }); continue; }
    for (const [name, roh] of Object.entries(d.inputSchema?.properties ?? {})) {
      const prop = roh as Prop;
      if (typeof prop?.description === 'string' && !KURZ_AUSNAHMEN.has(name) && kurzParameterText(d.name, name) === undefined) {
        fehlen.push({ tool: d.name, parameter: name });
      }
    }
  }
  return fehlen;
}
